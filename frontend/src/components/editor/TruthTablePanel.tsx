import type { TruthTableResponse } from '../../types/api'

interface TruthTablePanelProps {
  table: TruthTableResponse | null
  busy: boolean
  stale: boolean
  errors: string[]
  statusMessage: string | null
}

export default function TruthTablePanel({ table, busy, stale, errors, statusMessage }: TruthTablePanelProps) {
  const columns = table ? [
    ...table.inputs.map((column) => ({ ...column, kind: 'input' as const })),
    ...table.outputs.map((column) => ({ ...column, kind: 'output' as const })),
  ] : []

  return (
    <section className="truth-table-panel" aria-labelledby="truth-table-title">
      <div className="truth-table-heading">
        <div>
          <p className="panel-kicker">C++ ENGINE RESULT</p>
          <h3 id="truth-table-title">Truth Table</h3>
        </div>
        {stale && table && <span className="stale-results-badge">Table stale</span>}
      </div>

      {busy && (
        <p className="truth-table-status" role="status" aria-live="polite">
          {statusMessage ?? 'Generating truth table from the C++ engine…'}
        </p>
      )}
      {!busy && statusMessage && (
        <p className="truth-table-status" role="status" aria-live="polite">{statusMessage}</p>
      )}
      {stale && table && (
        <p className="truth-table-stale-message" role="status">
          The circuit has changed since this table was generated. Generate again to refresh it.
        </p>
      )}
      {errors.length > 0 && (
        <div className="truth-table-errors" role="alert">
          {errors.map((error, index) => <p key={`${index}-${error}`}>{error}</p>)}
        </div>
      )}

      {!table && !busy && errors.length === 0 && !statusMessage && (
        <p className="truth-table-empty">Generate a table to see every input assignment and its C++-computed outputs.</p>
      )}

      {table && !busy && errors.length === 0 && (
        <p className="truth-table-status" role="status" aria-live="polite">
          Truth table ready: {table.rows.length} rows, {table.inputs.length} inputs, {table.outputs.length} outputs.
        </p>
      )}

      {table && (
        <div className="truth-table-scroll" role="region" aria-label="Generated truth table" tabIndex={0}>
          <table>
            <caption>Truth table generated by the C++ simulation engine</caption>
            <thead>
              <tr>
                {columns.map((column, index) => (
                  <th
                    key={`${column.kind}-${column.id}-${index}`}
                    scope="col"
                    aria-label={`${column.name}, ${column.kind}, component ID ${column.id}`}
                    title={`Component ID ${column.id}`}
                    className={column.kind === 'output' ? 'truth-table-output-column' : undefined}
                  >
                    {column.name}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {table.rows.map((row, rowIndex) => {
                const values = [...row.inputs, ...row.outputs]
                return (
                  <tr key={rowIndex}>
                    {values.length > 0
                      ? values.map((value, columnIndex) => <td key={columnIndex}>{value}</td>)
                      : <td>—</td>}
                  </tr>
                )
              })}
              {table.rows.length === 0 && (
                <tr><td colSpan={Math.max(1, columns.length)}>No rows were returned.</td></tr>
              )}
            </tbody>
          </table>
        </div>
      )}
    </section>
  )
}
